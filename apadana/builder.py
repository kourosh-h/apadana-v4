"""
Builds the silica slab with alkylsilane SAMs on both of its faces and writes the GROMACS input files.

The SAMs are generated by introducing alkylsilane molecules at random binding locations on both
faces of the hydroxylated alpha-quartz (001) slab, such that both faces have the target surface
coverage. The binding locations of the two faces are chosen independently, so the two faces are
two different random arrangements of the same SAM.

Units follow GROMACS: lengths in nm and the box origin at a corner of the box. The z = 0 plane at
the center of the silica slab is used only in the README and the overview sheet of a system, never
in the GROMACS files.
"""
import os
import random
import shutil
from pathlib import Path

import numpy as np
from mbuild import Port
from mbuild.lib.atoms import H
from mbuild.lib.recipes import Monolayer
from parmed import gromacs

from .gromacs_files import (FORCEFIELD_FOLDER, number_gro_residues, read_topology_sections, remove_user_and_host,
                            write_index_file, write_molecule_itp, write_posres_files, write_topol_top)
from .molecules import Alkylsilane
from .reports import write_size_report, write_surface_readme, write_system_readme
from .surface import RENAMED_PDB, USER_SURFACE_PDB, SilicaSlab, default_tiles
from .visualize import plot_system
from .workflow import write_surface_workflow, write_workflow

DATA_FOLDER = Path(__file__).parent / 'data' / 'forcefield'
# foyer force-field file used to assign the atom types (the parameters come from the ForceField folder)
ATOM_TYPING_XML = DATA_FOLDER / 'EMAMI_CHARMM.xml'
FORCEFIELD_SOURCE = DATA_FOLDER / FORCEFIELD_FOLDER

# Name of the hydroxyl hydrogens and of the oxygens that become grafting points.
HYDROXYL_HYDROGEN = 'HD'
GRAFTING_OXYGEN = 'OP'


def number_of_chains(coverage, slab):
    """Number of chains on one face: coverage (molecules/nm^2) times the face area (nm^2), rounded."""
    n_chains = coverage * (slab.box.Lx * slab.box.Ly)
    return round(n_chains)


def is_on_face(z, z_middle, face):
    """True if an atom at height z belongs to the top face (above z_middle) or the bottom face (below)."""
    if face == 'top':
        return z > z_middle
    return z < z_middle


def add_grafting_ports(surface, n_chains, z_middle, face):
    """
    Choose n_chains random hydroxyl sites on one face and prepare them for grafting.

    The hydrogen of each chosen site is removed, its oxygen is renamed to OP, and a port is
    added on the oxygen, pointing away from the slab. face is 'top' (z > z_middle) or 'bottom'.
    """
    # The port of a top-face site points up (+z), that of a bottom-face site down (-z).
    if face == 'top':
        port_turn, port_shift, label = np.pi / 2, 0.1, 'port1'
    else:
        port_turn, port_shift, label = -np.pi / 2, -0.1, 'port2'

    hydroxyl_hydrogens = []
    for atom in list(surface.particles()):
        if atom.name == HYDROXYL_HYDROGEN and is_on_face(atom.pos[2], z_middle, face):
            hydroxyl_hydrogens.append(atom)
    print(f"Found {len(hydroxyl_hydrogens)} available hydroxyl sites on the {face} face.")

    print(f"Selecting random sites and adding {face} ports...")
    for hydrogen in random.sample(hydroxyl_hydrogens, k=n_chains):
        for oxygen in surface.bond_graph.neighbors(hydrogen):
            oxygen.name = GRAFTING_OXYGEN
        surface.remove(hydrogen)

    for atom in list(surface.particles()):
        if atom.name == GRAFTING_OXYGEN and is_on_face(atom.pos[2], z_middle, face):
            port = Port(anchor=atom)
            port.spin(port_turn, [1, 0, 0])
            port.translate(np.array([0.0, 0.0, port_shift]))
            surface.add(port, f"{label}_{len(surface.referenced_ports())}")


def find_atom_ids(system_name, sam_atom_names, surface_atom_names, n_chains_total):
    """
    Read the atom numbers of the silica and of the chains from {system_name}.itp.

    Returns (surface_ids, sam_ids, ids_per_chain); ids_per_chain has one list per grafted chain.
    """
    itp = read_topology_sections(f'{system_name}.itp')
    surface_ids = []
    sam_ids = []
    ids_per_chain = [[] for k in range(n_chains_total)]

    for line in itp['[ atoms ]']:
        columns = line.split()
        atom_number = int(columns[5])
        residue_number = int(columns[2])
        atom_name = columns[4]
        if atom_name in surface_atom_names:
            surface_ids.append(atom_number)
            surface_residue = residue_number
        if atom_name in sam_atom_names:
            sam_ids.append(atom_number)
            chain_index = (residue_number - surface_residue) - 1
            ids_per_chain[chain_index].append(atom_number)
    return surface_ids, sam_ids, ids_per_chain


def find_middle_layer(system_name, surface_resname, layer_width_nm):
    """
    Atom numbers of the silica atoms in the middle layer of the slab, the layer that is held in
    place by position restraints (the centermost 1 nm of the slab by default). Coordinates are
    read from {system_name}.gro with parmed, in Angstrom.

    Returns (middle_layer_ids, slab_center_nm), where slab_center_nm is the z of the slab center.
    """
    half_width = (layer_width_nm / 2) * 10
    gro = gromacs.GromacsGroFile.parse(f'{system_name}.gro')
    surface_atoms = [atom for atom in gro.atoms if atom.residue.name == surface_resname]

    surface_z = [atom.xz for atom in surface_atoms]
    middle = ((max(surface_z) - min(surface_z)) / 2) + min(surface_z)
    # parmed numbers the atoms from 0 (atom.idx), GROMACS from 1
    middle_layer_ids = [atom.idx + 1 for atom in surface_atoms
                        if middle - half_width < atom.xz < middle + half_width]
    return middle_layer_ids, middle / 10


def build_sam_system(chain_length,
                     coverage,
                     x_tiles=None,
                     y_tiles=None,
                     vacuum_space_nm=6,
                     restrained_layer_nm=1,
                     surface_resname='SUR',
                     sam_resname='OTS',
                     system_name='func',
                     surface_mode='slab',
                     user_surface=None,
                     output_folder='.',
                     random_seed=None,
                     hpc=None,
                     make_plot=True):
    """
    Build alkylsilane SAMs on both faces of the silica slab and write all GROMACS files.

    The silica slab is relaxed before the chains are grafted on it. There are three ways of use:
    1. surface_mode='slab' (default): the chains are grafted on the relaxed slab included in the
       package (7.86 x 7.66 nm, 12096 atoms).
    2. surface_mode='cell' with coverage=0: a new bare slab is built from x_tiles x y_tiles unit
       cells, together with the files to relax it in GROMACS (run_surface_relaxation.sh).
    3. surface_mode='user' with user_surface: the chains are grafted on a relaxed slab of the
       user (.gro or .pdb), for example the surface/2_npt_crescale/confout.gro of way 2.
    With coverage=0 in the modes 'slab' and 'user', the pristine slab gets the dry and wet workflow.

    chain_length        : number of carbon atoms in the alkyl chain, L (not used when coverage is 0)
    coverage            : grafting density on each face, Gamma (molecules/nm^2)
    x_tiles, y_tiles    : repeats of the silica structure in x and y; None (default) gives
                          8 x 9 unit cells in 'cell' mode (7.86 x 7.66 nm), else 1 x 1
    vacuum_space_nm     : empty space above and below the slab (nm)
    restrained_layer_nm : width of the middle silica layer that is restrained (nm)
    surface_resname     : residue name of the silica (SUR)
    sam_resname         : residue name of the alkylsilanes (OTS)
    system_name         : base name of the output files (func.gro, func.itp, ...)
    surface_mode        : 'slab', 'cell' or 'user' (see SilicaSlab)
    user_surface        : .gro or .pdb file of the slab for surface_mode='user'
    output_folder       : folder of the system; created if it does not exist. The structure and
                          topology go into output_folder/system, the workflow files next to it
    hpc                 : dictionary with SLURM settings of the run scripts, for example
                          {'account': 'my_account', 'partition': 'batch', 'time_production': '48:00:00'};
                          see HPC_DEFAULTS in workflow.py
    random_seed         : integer to make the choice of grafting sites reproducible;
                          None (default) gives a new random choice every time
    make_plot           : save system_overview.pdf (one A4 page) and .png: views of the built system,
                          its density profile, the grafting sites of both faces and the main numbers
                          (lengths in nm, z = 0 at the center of the silica slab)
    """
    if random_seed is not None:
        random.seed(random_seed)
        np.random.seed(random_seed)
    if x_tiles is None or y_tiles is None:
        x_tiles, y_tiles = default_tiles(surface_mode)
    # the files are written from inside output_folder/system, so the slab file needs its full path
    if user_surface is not None:
        user_surface = os.path.abspath(user_surface)
    # a new bare slab from unit cells is relaxed first; chains are grafted on it afterwards
    new_surface = (surface_mode == 'cell' and coverage == 0)

    start_folder = os.getcwd()
    output_folder = os.path.abspath(output_folder)
    system_folder = os.path.join(output_folder, 'system')
    os.makedirs(system_folder, exist_ok=True)
    os.chdir(system_folder)
    try:
        print("\n" + "-" * 50)
        print("STEP 1: INITIALIZING MOLECULES AND SURFACE")
        print("-" * 50)

        if coverage > 0:
            alkylsilane = Alkylsilane(n_ch2=(chain_length - 1), resname=sam_resname)
            molecule_top = alkylsilane.for_top_face()
            molecule_bottom = alkylsilane.for_bottom_face()
            backfill_hydrogen = H()

        silica = SilicaSlab(x_tiles=x_tiles, y_tiles=y_tiles, vacuum_space_nm=vacuum_space_nm,
                            resname=surface_resname)
        print(f"Loading surface in mode: {surface_mode} ({x_tiles} x {y_tiles})...")
        slab = silica.make_slab(mode=surface_mode, user_surface=user_surface)
        z_middle = slab.box.Lz / 2
        if surface_mode == 'cell' and coverage > 0:
            print("NOTE: the chains are grafted on unit cells that were not relaxed. To relax the slab first,")
            print("      build it with coverage=0, run run_surface_relaxation.sh and graft the chains on")
            print("      the relaxed slab with surface_mode='user'.")

        n_chains = number_of_chains(coverage, slab)
        print(f"Target coverage: {coverage} molecules/nm^2.")
        print(f"Number of grafted chains per face: {n_chains}")

        if n_chains > 0:
            print("\n" + "-" * 50)
            print("STEP 2: GRAFTING ON THE TOP FACE")
            print("-" * 50)
            add_grafting_ports(slab, n_chains, z_middle, face='top')
            print("Applying top monolayer...")
            slab_one_face = Monolayer(chains=[molecule_top], backfill=backfill_hydrogen, surface=slab,
                                      tile_x=1, tile_y=1)

            print("\n" + "-" * 50)
            print("STEP 3: GRAFTING ON THE BOTTOM FACE")
            print("-" * 50)
            add_grafting_ports(slab_one_face, n_chains, z_middle, face='bottom')
            print("Applying bottom monolayer...")
            system = Monolayer(chains=[molecule_bottom], backfill=backfill_hydrogen, surface=slab_one_face,
                               tile_x=1, tile_y=1)
        else:
            print("\nNo chains to graft: the system is the bare silica slab (STEPS 2 and 3 skipped).")
            system = slab

        print("\n" + "-" * 50)
        print("STEP 4: SAVING COORDINATES AND TOPOLOGY")
        print("-" * 50)
        residues = [sam_resname, silica.resname]
        print(f"Exporting files: {system_name}.pdb/mol2/gro")
        system.save(f'{system_name}.pdb', overwrite=True, residues=residues)
        system.save(f'{system_name}.mol2', overwrite=True, residues=residues)
        system.save(f'{system_name}.gro', overwrite=True, residues=residues)

        print("Assigning atom types and writing the GROMACS .top file...")
        system.save(f'{system_name}.top',
                    forcefield_files=ATOM_TYPING_XML, overwrite=True,
                    box=system.box, foyer_kwargs={"assert_bond_params": True, "assert_angle_params": True,
                                                  "assert_dihedral_params": True}, forcefield_debug=True,
                    residues=residues)
        remove_user_and_host(f'{system_name}.top')

        write_molecule_itp(system_name)
        number_gro_residues(system_name)
        write_topol_top(system_name)
        if not new_surface:
            write_topol_top(system_name, file_name='topol_wet.top', with_water=True)
        shutil.copytree(FORCEFIELD_SOURCE, FORCEFIELD_FOLDER, dirs_exist_ok=True)

        print("\n" + "-" * 50)
        print("STEP 5: INDEX GROUPS AND POSITION RESTRAINTS")
        print("-" * 50)
        sam_atom_names = []
        if n_chains > 0:
            sam_atom_names = [atom.name for atom in molecule_top.particles()]
        surface_atom_names = [atom.name for atom in slab.particles()]
        print("Mapping residues and atom indexes...")
        surface_ids, sam_ids, ids_per_chain = find_atom_ids(system_name, sam_atom_names, surface_atom_names,
                                                            n_chains * 2)
        middle_layer_ids, slab_center_nm = find_middle_layer(system_name, silica.resname, restrained_layer_nm)

        print("Writing index file and position-restraint files...")
        write_index_file(surface_ids, sam_ids, ids_per_chain, middle_layer_ids)
        write_posres_files(surface_ids, sam_ids, middle_layer_ids)
        write_size_report(system, chain_length, coverage, n_chains)
        settings = {'chain_length': chain_length, 'coverage': coverage, 'surface_mode': surface_mode,
                    'x_tiles': x_tiles, 'y_tiles': y_tiles, 'vacuum_space_nm': vacuum_space_nm,
                    'restrained_layer_nm': restrained_layer_nm, 'surface_resname': surface_resname,
                    'sam_resname': sam_resname, 'system_name': system_name, 'random_seed': random_seed}
        readme = os.path.join(output_folder, 'README.md')
        if new_surface:
            write_surface_workflow(output_folder, system_name, f'slab_{x_tiles}x{y_tiles}', hpc)
            write_surface_readme(readme, system_name, system, settings, len(surface_ids), slab_center_nm)
        else:
            write_workflow(output_folder, system_name, f'L{chain_length}_G{coverage}', hpc, with_chains=(n_chains > 0))
            write_system_readme(readme, system_name, system, settings, n_chains,
                                len(surface_ids), len(sam_ids), len(middle_layer_ids), slab_center_nm)
        for temporary_file in [RENAMED_PDB, USER_SURFACE_PDB]:
            if os.path.exists(temporary_file):
                os.remove(temporary_file)

        if make_plot:
            print("Plotting the overview sheet of the system...")
            workflow = 'surface' if new_surface else 'sam'
            for extension in ['pdf', 'png']:
                plot_system(f'{system_name}.gro', os.path.join(output_folder, f'system_overview.{extension}'),
                            chain_length, coverage, sam_resname=sam_resname, surface_resname=surface_resname,
                            restrained_layer_nm=restrained_layer_nm, settings=settings, workflow=workflow)

        print("\n" + "=" * 50)
        print(f"DONE: {system_name} is ready in {output_folder}")
        print("=" * 50 + "\n")
    finally:
        os.chdir(start_folder)


def functionalizer(x_size, y_size, chainLength, coverage, free_Space, width_mid, si_res_name,
                   alkylsilaneresname, namefuncsilica, surface_mode='slab', user_gro=None, user_pdb=None):
    """Earlier name and arguments of build_sam_system, kept so that older scripts still run."""
    user_surface = user_pdb
    if user_surface is None:
        user_surface = user_gro
    build_sam_system(chain_length=chainLength, coverage=coverage, x_tiles=x_size, y_tiles=y_size,
                     vacuum_space_nm=free_Space, restrained_layer_nm=width_mid,
                     surface_resname=si_res_name, sam_resname=alkylsilaneresname,
                     system_name=namefuncsilica, surface_mode=surface_mode, user_surface=user_surface)
